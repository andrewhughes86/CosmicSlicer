//! The engine fed hostile input: damaged G-code for the viewer, random values for any
//! setting, broken meshes. Each must give a result or an error, never a panic (for `slice`,
//! never `SliceError::Bug`), within the fuzz harness's time and memory limits. Run through
//! `tools/capped.sh`; `COSMICSLICER_FUZZ_ITERS` and `COSMICSLICER_FUZZ_SEED` as for the readers.

use super::*;
use CosmicSlicer_import::fuzz::{self, Rng};
use CosmicSlicer_model::{Mesh, primitives};
use glam::Vec3;

fn job(objects: Vec<JobObject>, process: Config, filament: Config) -> Job {
    let mut printer = Config::default();
    printer.set("printable_area", "0x0,220x0,220x220,0x220");
    Job {
        printer,
        process,
        filaments: vec![filament],
        bed_key: "textured_plate_temp".into(),
        bed_type_name: "Textured PEI Plate".into(),
        objects,
        plate_name: "Plate 1".into(),
        events: Vec::new(),
        calib: None,
    }
}

fn object(mesh: Mesh, at: Vec3) -> JobObject {
    JobObject {
        name: "fuzz".into(),
        mesh: Arc::new(mesh),
        matrix: Mat4::from_translation(at),
        extruder: 0,
        overrides: Vec::new(),
        support_volumes: Vec::new(),
        support_paint: Vec::new(),
        seam_paint: Vec::new(),
        fuzzy_paint: Vec::new(),
        color_paint: Vec::new(),
        brim_ears: Vec::new(),
        volumes: Vec::new(),
        ranges: Vec::new(),
        layer_profile: Vec::new(),
    }
}

/// Slices, failing only on an engine bug; counts the jobs that gave G-code in `sliced`.
fn slice_ok(job: &Job, sliced: &mut usize) -> Result<(), String> {
    match slice(job, &Progress::default()) {
        Err(SliceError::Bug(e)) => Err(e),
        Err(_) => Ok(()),
        Ok(out) => {
            *sliced += 1;
            let bad = out.gcode.lines().find(|l| {
                let code = l.split(';').next().unwrap_or("").to_ascii_lowercase();
                code.contains("nan") || code.contains("inf") || code.contains('{')
            });
            match bad {
                Some(l) => Err(format!("G-code line {l:?}")),
                None => Ok(()),
            }
        }
    }
}

fn sliced_cube() -> String {
    let j =
        job(vec![object(primitives::cube(10.0), Vec3::new(100.0, 100.0, 0.0))], Config::default(), Config::default());
    slice(&j, &Progress::default()).map(|s| s.gcode).unwrap_or_default()
}

#[test]
fn the_gcode_viewer_survives_damaged_files() {
    let schema = Schema::get();
    let s = Settings::read(schema, &Config::default());
    let fil = vec![Filament::read(schema, &Config::default(), "textured_plate_temp")];
    let ours = sliced_cube();
    assert!(ours.len() > 1000);
    let others = "; generated by PrusaSlicer\nG21\nG90\nM82\nM104 S215\nG28\nG92 E0\n;LAYER_CHANGE\n;Z:0.2\n\
        G1 Z.2 F720\n;TYPE:External perimeter\n;WIDTH:0.45\nG1 X10 Y10 E1.5 F1200\nG2 X20 Y10 I5 J0 E2\n\
        G3 X10 Y10 R5 E2.5\nG10\nG11\nM106 S255\nT1\nG91\nG1 Z1\nG90\nM73 P50 R3\n;LAYER:1\n;TYPE:FILL\n\
        G0 X0 Y0\nG1 X50 Y50 E9 F3000\nM107\nM84\n";
    let failures = fuzz::run("gcode", &[ours.into_bytes(), others.as_bytes().to_vec()], &|b| {
        let v = gcodeview::read(&String::from_utf8_lossy(b), &s, &fil);
        assert!(v.stats.total_time.is_finite() && v.stats.total_time >= 0.0, "{}", v.stats.total_time);
    });
    assert!(failures.is_empty(), "{failures:#?}");
}

/// Values that break careless settings code, for an option of `kind`.
fn hostile_value(rng: &mut Rng, def: &CosmicSlicer_config::OptionDef) -> String {
    use CosmicSlicer_config::OptionType;
    let number = |rng: &mut Rng| -> String {
        let pick = ["0", "-0", "-1", "1e9", "-1e9", "1e-9", "nan", "inf", "-inf", "", "abc", "0.0001", "100000", "3"];
        match rng.below(4) {
            0 => def.min.map_or("0".into(), |m| m.to_string()),
            1 => def.max.map_or("1".into(), |m| m.to_string()),
            _ => pick.get(rng.below(pick.len())).copied().unwrap_or("0").to_owned(),
        }
    };
    let one = |rng: &mut Rng| -> String {
        match def.kind() {
            OptionType::Float | OptionType::Int => number(rng),
            OptionType::Percent | OptionType::FloatOrPercent => {
                let n = number(rng);
                if rng.chance(2) { format!("{n}%") } else { n }
            }
            OptionType::Bool => ["0", "1", "2", "", "true"].get(rng.below(5)).copied().unwrap_or("0").to_owned(),
            OptionType::Enum => match def.enum_values.get(rng.below(def.enum_values.len() + 1)) {
                Some((v, _)) => v.clone(),
                None => "no_such_value".into(),
            },
            OptionType::Point | OptionType::Points => {
                ["0x0", "1e9x-1e9", "nanx1", "", "0x0,0x0,0x0", "x"].get(rng.below(6)).copied().unwrap_or("").into()
            }
            OptionType::String | OptionType::Other => [
                "",
                "{",
                "}",
                "{if}",
                "[layer_num]",
                "{layer_z * 1e999}",
                "{undefined_variable}",
                "G1 X{1/0}",
                "M117 hi\n{endif}",
                "\u{0}",
            ]
            .get(rng.below(10))
            .copied()
            .unwrap_or("")
            .into(),
        }
    };
    if def.is_vector() && rng.chance(3) {
        (0..rng.below(4)).map(|_| one(rng)).collect::<Vec<_>>().join(",")
    } else {
        one(rng)
    }
}

#[test]
fn any_setting_value_slices_or_says_why() {
    let schema = Schema::get();
    let mut keys: Vec<&String> = schema.options.keys().collect();
    keys.sort();
    // Half the picks from the options the engine reads (named in `settings.rs`), or most
    // cases would only change settings nothing looks at.
    let read: Vec<&String> = include_str!("settings.rs")
        .split('"')
        .skip(1)
        .step_by(2)
        .filter_map(|k| schema.options.get_key_value(k).map(|(k, _)| k))
        .collect();
    assert!(read.len() > 100, "{}", read.len());
    let seed = fuzz::seed_for("settings", 0);
    let mut rng = Rng::new(seed);
    let mut failures = Vec::new();
    let (cases, mut sliced) = ((fuzz::iterations() / 5).max(1), 0);
    for i in 0..cases {
        let (mut process, mut filament) = (Config::default(), Config::default());
        let mut changed = Vec::new();
        for _ in 0..1 + rng.below(8) {
            let pool = if rng.chance(2) { &read } else { &keys };
            let Some(key) = pool.get(rng.below(pool.len())) else { continue };
            let Some(def) = schema.option(key) else { continue };
            let value = hostile_value(&mut rng, def);
            process.set((*key).clone(), value.clone());
            filament.set((*key).clone(), value.clone());
            changed.push(format!("{key} = {value:?}"));
        }
        let size = [10.0, 1.0, 0.3][rng.below(3)];
        let j = job(vec![object(primitives::cube(size), Vec3::new(100.0, 100.0, 0.0))], process, filament);
        let input = format!("{size} mm cube\n{}\n", changed.join("\n"));
        if let Some(f) =
            fuzz::guard(&format!("settings-case{i}-seed{seed:#x}"), input.as_bytes(), &mut || slice_ok(&j, &mut sliced))
        {
            failures.push(format!("{f}\n  {}", changed.join("\n  ")));
            if failures.len() > 5 {
                break;
            }
        }
    }
    assert!(failures.is_empty(), "{failures:#?}");
    // Hostile values must not all be refused up front, or nothing past that was tested.
    eprintln!("settings: {sliced} of {cases} cases gave G-code");
    assert!(sliced * 3 >= cases, "only {sliced} of {cases} cases sliced");
}

/// A cube or cylinder broken at random: vertices moved far or onto each other, triangles
/// dropped, flipped or repeated, indices out of range, coordinates not finite.
fn broken_mesh(rng: &mut Rng) -> Mesh {
    let mut m = if rng.chance(2) { primitives::cube(10.0) } else { primitives::cylinder(5.0, 10.0, 24) };
    for _ in 0..1 + rng.below(6) {
        let nv = m.vertices.len();
        let nt = m.triangles.len();
        match rng.below(8) {
            0 => {
                if let Some(v) = m.vertices.get_mut(rng.below(nv)) {
                    *v += Vec3::new(rng.unit() as f32, rng.unit() as f32, rng.unit() as f32) * 20.0;
                }
            }
            1 => {
                let (a, b) = (rng.below(nv), rng.below(nv));
                if let Some(&p) = m.vertices.get(a)
                    && let Some(v) = m.vertices.get_mut(b)
                {
                    *v = p;
                }
            }
            2 if nt > 0 => {
                m.triangles.remove(rng.below(nt));
            }
            3 => {
                if let Some(t) = m.triangles.get_mut(rng.below(nt)) {
                    t.swap(1, 2);
                }
            }
            4 => {
                if let Some(&t) = m.triangles.get(rng.below(nt)) {
                    m.triangles.push(t);
                }
            }
            5 => {
                if let Some(t) = m.triangles.get_mut(rng.below(nt)) {
                    t[rng.below(3)] = [nv as u32, u32::MAX, 0][rng.below(3)];
                }
            }
            6 => {
                if let Some(v) = m.vertices.get_mut(rng.below(nv)) {
                    v.x = [f32::NAN, f32::INFINITY, 1.0e30, -1.0e-30][rng.below(4)];
                }
            }
            _ => {
                let s = [1.0e-4f32, 1.0e3, 0.0, -1.0][rng.below(4)];
                for v in &mut m.vertices {
                    v.z *= s;
                }
            }
        }
    }
    m
}

#[test]
fn broken_meshes_slice_or_say_why() {
    let seed = fuzz::seed_for("meshes", 0);
    let mut rng = Rng::new(seed);
    let mut failures = Vec::new();
    let (cases, mut sliced) = ((fuzz::iterations() / 5).max(1), 0);
    for i in 0..cases {
        let mesh = broken_mesh(&mut rng);
        let input = format!("{:?}\n{:?}\n", mesh.vertices, mesh.triangles);
        let j = job(vec![object(mesh, Vec3::new(100.0, 100.0, 0.0))], Config::default(), Config::default());
        if let Some(f) =
            fuzz::guard(&format!("mesh-case{i}-seed{seed:#x}"), input.as_bytes(), &mut || slice_ok(&j, &mut sliced))
        {
            failures.push(f);
            if failures.len() > 5 {
                break;
            }
        }
    }
    assert!(failures.is_empty(), "{failures:#?}");
    eprintln!("meshes: {sliced} of {cases} cases gave G-code");
    assert!(sliced * 3 >= cases, "only {sliced} of {cases} cases sliced");
}
